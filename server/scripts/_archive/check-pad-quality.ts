import { PrismaClient } from '@prisma/client';

const prisma = new PrismaClient();

async function main() {
  console.log('='.repeat(80));
  console.log('PAD / WELL DATA QUALITY ANALYSIS');
  console.log('='.repeat(80));

  // 1. Deep Creek pads
  console.log('\n' + '-'.repeat(80));
  console.log('1) PADS MATCHING "deep creek" (case-insensitive)');
  console.log('-'.repeat(80));

  const deepCreekPads = await prisma.pad.findMany({
    where: { name: { contains: 'deep creek', mode: 'insensitive' } },
    include: {
      wells: { select: { id: true, wellName: true, wellNameBase: true, apiNumber: true, wellType: true, wellStatus: true } },
      field: { select: { name: true } },
      currentOperator: { select: { name: true } },
      _count: { select: { wells: true, workPoints: true } },
    },
    orderBy: { name: 'asc' },
  });

  console.log('Found ' + deepCreekPads.length + ' pads:');
  for (const pad of deepCreekPads) {
    console.log('\n  PAD: ' + pad.name);
    console.log('    Field: ' + pad.field.name + ' | Operator: ' + (pad.currentOperator?.name || 'N/A'));
    console.log('    Wells: ' + pad._count.wells + ' | WorkPoints: ' + pad._count.workPoints);
    console.log('    AutoGen: ' + pad.autoGenerated + ' | PendingReview: ' + pad.pendingReview);
    if (pad.wells.length > 0) {
      for (const w of pad.wells) {
        console.log('      WELL: ' + (w.wellName || 'NULL') + ' | Base: ' + (w.wellNameBase || 'NULL') + ' | API: ' + (w.apiNumber || 'NULL') + ' | ' + (w.wellType || '?') + '/' + (w.wellStatus || '?'));
      }
    } else {
      console.log('      (no wells)');
    }
  }

  // 2. Count pads with 0 wells
  console.log('\n' + '-'.repeat(80));
  console.log('2) PADS WITH ZERO WELLS');
  console.log('-'.repeat(80));

  const totalPads = await prisma.pad.count();
  const padsWithWells = await prisma.pad.count({ where: { wells: { some: {} } } });
  const padsWithZeroWells = totalPads - padsWithWells;

  console.log('Total pads: ' + totalPads);
  console.log('Pads with >= 1 well: ' + padsWithWells);
  console.log('Pads with 0 wells: ' + padsWithZeroWells + ' (' + ((padsWithZeroWells / totalPads) * 100).toFixed(1) + '%)');

  const sampleEmpty = await prisma.pad.findMany({
    where: { wells: { none: {} } },
    select: {
      name: true, autoGenerated: true, pendingReview: true,
      field: { select: { name: true } },
      currentOperator: { select: { name: true } },
    },
    orderBy: { name: 'asc' },
    take: 25,
  });
  console.log('\nSample of pads with 0 wells (first 25):');
  for (const p of sampleEmpty) {
    console.log('  ' + p.name.padEnd(50) + ' | ' + p.field.name.padEnd(25) + ' | ' + (p.currentOperator?.name || 'N/A').substring(0, 30) + ' | autoGen=' + p.autoGenerated);
  }

  // 3. Pads whose names look like well names
  console.log('\n' + '-'.repeat(80));
  console.log('3) PADS WITH WELL-LIKE NAMES');
  console.log('-'.repeat(80));

  const allPads = await prisma.pad.findMany({
    select: {
      id: true, name: true, autoGenerated: true, pendingReview: true,
      field: { select: { name: true } },
      _count: { select: { wells: true } },
    },
    orderBy: { name: 'asc' },
  });

  const wellPatterns = [
    /\d+[A-Z]*-\d+H\b/i,
    /#\d+/,
    /\b\d+-\d+[HV]\b/i,
    /\bSWD\b/i,
    /\b\d+X-\d+H\b/i,
    /\b\d+-\d+-\d+H\b/i,
    /\bH-\d+/i,
    /\d+H$/,
  ];

  const wellLikePads = allPads.filter((p: any) => wellPatterns.some(rx => rx.test(p.name)));

  console.log('Total pads: ' + allPads.length);
  console.log('Pads with well-like names: ' + wellLikePads.length + ' (' + ((wellLikePads.length / allPads.length) * 100).toFixed(1) + '%)');

  const autoGenWellLike = wellLikePads.filter((p: any) => p.autoGenerated).length;
  const manualWellLike = wellLikePads.filter((p: any) => !p.autoGenerated).length;
  console.log('  Auto-generated: ' + autoGenWellLike + ' | Manual: ' + manualWellLike);

  const wellLikeNoWells = wellLikePads.filter((p: any) => p._count.wells === 0).length;
  const wellLikeWithWells = wellLikePads.filter((p: any) => p._count.wells > 0).length;
  console.log('  With 0 wells: ' + wellLikeNoWells + ' | With >= 1 well: ' + wellLikeWithWells);

  console.log('\nSample of well-like pad names (first 40):');
  for (const p of wellLikePads.slice(0, 40)) {
    console.log('  ' + p.name.padEnd(55) + ' | wells=' + String(p._count.wells).padStart(2) + ' | ' + p.field.name.padEnd(20) + ' | autoGen=' + p.autoGenerated);
  }
  if (wellLikePads.length > 40) {
    console.log('  ... and ' + (wellLikePads.length - 40) + ' more');
  }

  // 4. Deep Creek Federal 43X-05H - work points with bottle data
  console.log('\n' + '-'.repeat(80));
  console.log('4) "Deep Creek Federal 43X-05H" - WORK POINTS & BOTTLE DATA');
  console.log('-'.repeat(80));

  const targetPad = await prisma.pad.findFirst({
    where: { name: { contains: 'Deep Creek Federal 43X-05H', mode: 'insensitive' } },
    include: {
      field: { select: { name: true } },
      currentOperator: { select: { name: true } },
      workPoints: {
        include: {
          airSystemInspections: {
            select: {
              id: true, workPointName: true, airSystemType: true,
              reelSerialNumber: true, standSerialNumber: true,
              overallResult: true, cylinders: true,
              cylinderSerialNumber: true, cylinderPsi: true,
              cascadePsi: true, cascadeArrivalPsi: true, cascadeDeparturePsi: true,
              cylinderHydroDate: true, cylinderExpiryDate: true, inspectedAt: true,
            },
            orderBy: { inspectedAt: 'desc' },
            take: 5,
          },
        },
      },
      wells: {
        select: {
          id: true, wellName: true, apiNumber: true,
          workPoints: {
            include: {
              airSystemInspections: {
                select: {
                  id: true, workPointName: true, airSystemType: true,
                  reelSerialNumber: true, standSerialNumber: true,
                  overallResult: true, cylinders: true,
                  cylinderSerialNumber: true, cylinderPsi: true,
                  cascadePsi: true, cascadeArrivalPsi: true, cascadeDeparturePsi: true,
                  cylinderHydroDate: true, cylinderExpiryDate: true, inspectedAt: true,
                },
                orderBy: { inspectedAt: 'desc' },
                take: 5,
              },
            },
          },
        },
      },
    },
  });

  if (!targetPad) {
    console.log('Exact pad match not found. Searching for close matches...');
    const candidates = await prisma.pad.findMany({
      where: { name: { contains: 'Deep Creek', mode: 'insensitive' } },
      select: { id: true, name: true },
      orderBy: { name: 'asc' },
    });
    console.log('Candidate pads:');
    for (const c of candidates) console.log('  ' + c.name);

    const wellMatches = await prisma.well.findMany({
      where: { wellName: { contains: 'Deep Creek Federal 43X-05H', mode: 'insensitive' } },
      select: {
        id: true, wellName: true,
        pad: { select: { id: true, name: true } },
        workPoints: {
          include: {
            airSystemInspections: {
              select: {
                id: true, workPointName: true, cylinders: true,
                cylinderSerialNumber: true, cylinderPsi: true,
                cascadePsi: true, cascadeArrivalPsi: true, cascadeDeparturePsi: true,
                inspectedAt: true, overallResult: true, airSystemType: true,
                reelSerialNumber: true, standSerialNumber: true,
                cylinderHydroDate: true, cylinderExpiryDate: true,
              },
              orderBy: { inspectedAt: 'desc' },
              take: 5,
            },
          },
        },
      },
    });
    if (wellMatches.length > 0) {
      console.log('\nFound as WELL name(s) instead:');
      for (const wm of wellMatches) {
        console.log('  Well: ' + wm.wellName + ' | On Pad: ' + (wm.pad?.name || 'NONE'));
        for (const wp of wm.workPoints) {
          console.log('    WorkPoint: ' + wp.name + ' | type=' + wp.workPointType);
          printInspections(wp.airSystemInspections, '      ');
        }
      }
    } else {
      console.log('Not found as a well either.');
    }
  } else {
    console.log('PAD: ' + targetPad.name);
    console.log('  Field: ' + targetPad.field.name + ' | Operator: ' + (targetPad.currentOperator?.name || 'N/A'));

    console.log('\n  Pad-level WorkPoints (' + targetPad.workPoints.length + '):');
    for (const wp of targetPad.workPoints) {
      console.log('    WorkPoint: ' + wp.name + ' | type=' + wp.workPointType + ' | hasAir=' + wp.hasSuppliedAir);
      console.log('      Reel SN: ' + (wp.reelSerialNumber || 'N/A') + ' | Stand SN: ' + (wp.standSerialNumber || 'N/A'));
      printInspections(wp.airSystemInspections, '      ');
    }

    console.log('\n  Well-level data (' + targetPad.wells.length + ' wells):');
    for (const well of targetPad.wells) {
      console.log('    WELL: ' + (well.wellName || 'N/A') + ' | API: ' + (well.apiNumber || 'N/A'));
      if (well.workPoints.length > 0) {
        for (const wp of well.workPoints) {
          console.log('      WorkPoint: ' + wp.name + ' | type=' + wp.workPointType + ' | hasAir=' + wp.hasSuppliedAir);
          console.log('        Reel SN: ' + (wp.reelSerialNumber || 'N/A') + ' | Stand SN: ' + (wp.standSerialNumber || 'N/A'));
          printInspections(wp.airSystemInspections, '        ');
        }
      } else {
        console.log('      (no work points)');
      }
    }
  }

  // Summary
  console.log('\n' + '='.repeat(80));
  console.log('SUMMARY');
  console.log('='.repeat(80));
  const totalWells = await prisma.well.count();
  const orphanWells = await prisma.well.count({ where: { padId: null } });
  const totalWorkPoints = await prisma.workPoint.count();
  const wpOnPads = await prisma.workPoint.count({ where: { padId: { not: null } } });
  const wpOnWells = await prisma.workPoint.count({ where: { wellId: { not: null } } });
  const wpOrphan = await prisma.workPoint.count({ where: { padId: null, wellId: null, facilityId: null } });

  console.log('Total pads: ' + totalPads + ' | Total wells: ' + totalWells + ' | Total work points: ' + totalWorkPoints);
  console.log('Pads with 0 wells: ' + padsWithZeroWells + ' (' + ((padsWithZeroWells / totalPads) * 100).toFixed(1) + '%)');
  console.log('Wells with no pad (orphaned): ' + orphanWells + ' (' + ((orphanWells / totalWells) * 100).toFixed(1) + '%)');
  console.log('Pads with well-like names: ' + wellLikePads.length + ' (' + ((wellLikePads.length / allPads.length) * 100).toFixed(1) + '%)');
  console.log('Work points on pads: ' + wpOnPads + ' | on wells: ' + wpOnWells + ' | orphaned: ' + wpOrphan);
  console.log('');

  await prisma.$disconnect();
}

function printInspections(inspections: any[], indent: string) {
  if (inspections.length === 0) {
    console.log(indent + '(no inspections)');
    return;
  }
  console.log(indent + 'Recent Inspections (' + inspections.length + '):');
  for (const insp of inspections) {
    console.log(indent + '  ' + insp.inspectedAt + ' | result=' + insp.overallResult + ' | type=' + (insp.airSystemType || 'N/A'));
    console.log(indent + '  reelSN=' + (insp.reelSerialNumber || 'N/A') + ' | standSN=' + (insp.standSerialNumber || 'N/A'));
    console.log(indent + '  cylPsi=' + (insp.cylinderPsi ?? 'N/A') + ' | cascArr=' + (insp.cascadeArrivalPsi ?? 'N/A') + ' | cascDep=' + (insp.cascadeDeparturePsi ?? 'N/A'));
    console.log(indent + '  cylSN=' + (insp.cylinderSerialNumber || 'N/A') + ' | hydroDate=' + (insp.cylinderHydroDate || 'N/A') + ' | expiry=' + (insp.cylinderExpiryDate || 'N/A'));
    if (insp.cylinders) {
      const cyls = Array.isArray(insp.cylinders) ? insp.cylinders : [];
      console.log(indent + '  Cylinders JSONB (' + cyls.length + '):');
      for (const cyl of cyls as any[]) {
        console.log(indent + '    SN=' + (cyl.serialNumber || '?') + ' | hydro=' + (cyl.hydroDate || '?') + ' | expiry=' + (cyl.expiryDate || '?') + ' | condition=' + (cyl.condition || '?') + ' | replaced=' + (cyl.replaced || false));
      }
    }
  }
}

main().catch(e => { console.error(e); process.exit(1); });