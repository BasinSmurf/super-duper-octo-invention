/** Preserve handoff provenance when the wizard replaces its editable metadata.
 * Do not merge the whole old object: omitted wizard drafts and form fields must
 * still be removable on completion/correction.
 */
export function preserveTicketOrigin(incoming: any, existing: any): any {
  if (incoming === undefined) return undefined;
  const origin: Record<string, unknown> = {};
  for (const key of ['classproSessionId', 'autoGeneratedFrom']) {
    if (existing?.[key] != null) origin[key] = existing[key];
  }
  return Object.keys(origin).length ? { ...incoming, ...origin } : incoming;
}
