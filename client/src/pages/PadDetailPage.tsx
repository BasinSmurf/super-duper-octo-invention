import { useState, useEffect, useCallback } from 'react'
import { useParams, useNavigate } from 'react-router-dom'
import { useAuth } from '@/contexts/AuthContext'
import { api } from '@/lib/api'
import { cn } from '@/lib/cn'
import { hasPermission } from '@/lib/permissions'
import { AddWellModal } from '@/components/AddWellModal'
import { LocationWorkPointEditor } from '@/components/LocationWorkPointEditor'
import {
  ArrowLeft,
  Building2,
  Droplets,
  Wind,
  Navigation,
  ChevronRight,
  Loader2,
  AlertTriangle,
  CheckCircle,
  Shield,
  Compass,
  Plus,
  Layers,
  MapPin,
  ArrowRightLeft,
  X,
  Search,
  Unlink,
  Tag,
} from 'lucide-react'

const ASSET_CATEGORY_LABELS: Record<string, string> = {
  rig: 'Drilling rig',
  truck: 'Service truck',
  other_mobile: 'Mobile asset',
  gas_plant: 'Gas plant',
  tank_battery: 'Tank battery',
  compressor_station: 'Compressor station',
  swd_facility: 'SWD facility',
  office: 'Office',
  shop: 'Shop',
}

// ---- Types ----
interface WellInfo {
  id: string
  wellName: string | null
  apiNumber: string | null
  wellType: string | null
  wellStatus: string | null
  hasSuppliedAir: boolean
  hasAreaMonitors: boolean
  isHighRisk: boolean
  riskNotes: string | null
  serviceNotes: string | null
}

interface WorkPointInfo {
  id: string
  name: string
  type: string
  isActive: boolean
  customData: any
}

interface PadDetail {
  id: string
  name: string
  isActive: boolean
  pendingReview: boolean
  autoGenerated: boolean
  manuallyVerified: boolean
  tier1: boolean
  assetCategory: 'site' | 'other_mobile'
    | 'gas_plant' | 'tank_battery' | 'compressor_station' | 'swd_facility' | 'office' | 'shop'
  section: number | null
  township: number | null
  range: number | null
  latitude: string | null
  longitude: string | null
  county: string | null
  directions: string | null
  accessNotes: string | null
  facilityCode: string | null
  customData: any
  createdAt: string
  updatedAt: string
  field: { id: string; name: string; county: string | null; state: string | null } | null
  currentOperator: { id: string; name: string } | null
  wells: WellInfo[]
  workPoints: WorkPointInfo[]
}

const WELL_STATUS_LABELS: Record<string, string> = {
  A: 'Active', DRY: 'Dry Hole', PA: 'Plugged', PNC: 'P&C',
  IA: 'Inactive', SI: 'Shut In', TA: 'Temp Abandoned',
  LOC: 'Location', WC: 'Waiting Completion', DC: 'Drilling Complete',
}

const WELL_TYPE_LABELS: Record<string, string> = {
  OG: 'Oil & Gas', SWD: 'Salt Water Disposal', WI: 'Water Injection',
  GI: 'Gas Injection', OB: 'Observation', ST: 'Stratigraphic Test',
}

function formatDate(d: string | null): string {
  if (!d) return '---'
  return new Date(d).toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' })
}

export function PadDetailPage() {
  const { id } = useParams<{ id: string }>()
  const navigate = useNavigate()
  const { user } = useAuth()
  const canManage = hasPermission(user?.role, 'locations:manage')
  const [pad, setPad] = useState<PadDetail | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)
  const [showAddWell, setShowAddWell] = useState(false)
  // Well reassignment state
  const [movingWellId, setMovingWellId] = useState<string | null>(null)
  const [padSearch, setPadSearch] = useState('')
  const [padResults, setPadResults] = useState<{ id: string; name: string; field?: { name: string } | null }[]>([])
  const [padSearching, setPadSearching] = useState(false)
  // Facility code inline edit
  const [editingFacility, setEditingFacility] = useState(false)
  const [facilityDraft, setFacilityDraft] = useState('')
  const [savingFacility, setSavingFacility] = useState(false)

  const loadPad = useCallback(async () => {
    if (!id) return
    setLoading(true)
    setError(null)
    try {
      const data = await api.get<PadDetail>(`/locations/pads/${id}`)
      setPad(data)
    } catch (e: any) {
      setError(e.message || 'Failed to load pad')
    } finally {
      setLoading(false)
    }
  }, [id])

  useEffect(() => { loadPad() }, [loadPad])

  // Search for pads to move a well to
  useEffect(() => {
    if (!padSearch || padSearch.length < 2) { setPadResults([]); return }
    const t = setTimeout(async () => {
      setPadSearching(true)
      try {
        const operatorId = pad?.currentOperator?.id || ''
        const qs = operatorId ? `&operatorId=${operatorId}` : ''
        const res = await api.get<{ data: typeof padResults }>(`/locations/pads?search=${encodeURIComponent(padSearch)}${qs}&limit=8`)
        setPadResults((res.data || []).filter(p => p.id !== id)) // exclude current pad
      } catch { setPadResults([]) }
      finally { setPadSearching(false) }
    }, 300)
    return () => clearTimeout(t)
  }, [padSearch, pad?.currentOperator?.id, id])

  const handleMoveToPad = async (wellId: string, targetPadId: string) => {
    try {
      await api.put(`/locations/wells/${wellId}/reassign`, { padId: targetPadId })
      setMovingWellId(null)
      setPadSearch('')
      loadPad() // refresh — well will disappear from this pad
    } catch (e: any) {
      alert(e.message || 'Failed to move well')
    }
  }

  const handleUnassignWell = async (wellId: string) => {
    try {
      await api.put(`/locations/wells/${wellId}/reassign`, { padId: null })
      setMovingWellId(null)
      loadPad()
    } catch (e: any) {
      alert(e.message || 'Failed to unassign well')
    }
  }

  const handleSaveFacility = async () => {
    if (!pad) return
    const value = facilityDraft.trim() || null
    setSavingFacility(true)
    try {
      await api.put(`/locations/pads/${pad.id}`, { facilityCode: value })
      setPad({ ...pad, facilityCode: value })
      setEditingFacility(false)
    } catch (e: any) {
      alert(e.message || 'Failed to update facility code')
    } finally {
      setSavingFacility(false)
    }
  }

  const handleToggleTier1 = async () => {
    if (!pad) return
    const next = !pad.tier1
    setPad({ ...pad, tier1: next })  // optimistic
    try {
      await api.put(`/locations/pads/${pad.id}`, { tier1: next })
    } catch (e: any) {
      setPad({ ...pad, tier1: !next })  // revert
      alert(e.message || 'Failed to update Tier 1')
    }
  }

  const handleAssetCategoryChange = async (next: PadDetail['assetCategory']) => {
    if (!pad) return
    const prev = pad.assetCategory
    setPad({ ...pad, assetCategory: next })  // optimistic
    try {
      await api.put(`/locations/pads/${pad.id}`, { assetCategory: next })
    } catch (e: any) {
      setPad({ ...pad, assetCategory: prev })  // revert
      alert(e.message || 'Failed to update asset type')
    }
  }

  if (loading) {
    return (
      <div className="flex items-center justify-center py-20">
        <Loader2 className="w-6 h-6 animate-spin text-blue-500" />
        <span className="ml-2 text-gray-500">Loading pad...</span>
      </div>
    )
  }

  if (error || !pad) {
    return (
      <div className="max-w-3xl mx-auto px-4 py-6">
        <button onClick={() => navigate(-1)} className="flex items-center gap-1 text-sm text-gray-500 hover:text-gray-700 mb-4">
          <ArrowLeft className="w-4 h-4" /> Back
        </button>
        <div className="bg-red-50 border border-red-200 text-red-700 px-4 py-3 rounded-lg text-sm">
          {error || 'Pad not found'}
        </div>
      </div>
    )
  }

  const str = [pad.section, pad.township, pad.range].filter(v => v != null)
  const strLabel = str.length === 3 ? `S${str[0]} T${str[1]}N R${str[2]}W` : null
  const hasGps = pad.latitude && pad.longitude
  const azureLocationId = pad.customData?.azureLocationId

  return (
    <div className="max-w-3xl mx-auto px-4 py-6 space-y-6">
      {/* Header */}
      <div>
        <button onClick={() => navigate('/locations')} className="flex items-center gap-1 text-sm text-gray-500 hover:text-gray-700 mb-3">
          <ArrowLeft className="w-4 h-4" /> Locations
        </button>
        <div className="flex items-start gap-3">
          <div className="w-12 h-12 rounded-xl bg-emerald-50 flex items-center justify-center flex-shrink-0">
            <Layers className="w-6 h-6 text-emerald-600" />
          </div>
          <div className="flex-1 min-w-0">
            <h1 className="text-xl font-bold text-gray-900">{pad.name}</h1>
            <div className="flex items-center flex-wrap gap-2 mt-1">
              {pad.currentOperator && (
                <button
                  onClick={() => navigate(`/companies/${pad.currentOperator!.id}`)}
                  className="text-xs bg-blue-50 text-blue-700 px-2 py-0.5 rounded-full hover:bg-blue-100 flex items-center gap-1"
                >
                  <Building2 className="w-3 h-3" />{pad.currentOperator.name}
                </button>
              )}
              {pad.pendingReview && (
                <span className="text-xs bg-amber-100 text-amber-700 px-2 py-0.5 rounded-full flex items-center gap-1">
                  <AlertTriangle className="w-3 h-3" /> Pending Review
                </span>
              )}
              {pad.manuallyVerified && (
                <span className="text-xs bg-green-100 text-green-700 px-2 py-0.5 rounded-full flex items-center gap-1">
                  <CheckCircle className="w-3 h-3" /> Verified
                </span>
              )}
              {canManage ? (
                <button
                  onClick={handleToggleTier1}
                  className={cn(
                    'text-xs px-2 py-0.5 rounded-full flex items-center gap-1 transition-colors',
                    pad.tier1
                      ? 'bg-purple-100 text-purple-700 hover:bg-purple-200'
                      : 'bg-gray-100 text-gray-500 hover:bg-gray-200',
                  )}
                  title={pad.tier1 ? 'On a reservation — click to clear' : 'Mark this pad as on a reservation'}
                >
                  <MapPin className="w-3 h-3" />
                  {pad.tier1 ? 'Tier 1' : 'Not Tier 1'}
                </button>
              ) : pad.tier1 ? (
                <span className="text-xs bg-purple-100 text-purple-700 px-2 py-0.5 rounded-full flex items-center gap-1">
                  <MapPin className="w-3 h-3" /> Tier 1
                </span>
              ) : null}
              {canManage ? (
                <select
                  value={pad.assetCategory}
                  onChange={e => handleAssetCategoryChange(e.target.value as PadDetail['assetCategory'])}
                  title="Rigs/trucks bypass operator-scoped dedup so the same record is reused for every operator they work for. Gas plants/offices/etc. stay scoped to this operator — they just never get a DMR match."
                  className={cn(
                    'text-xs px-2 py-0.5 rounded-full border-0 cursor-pointer',
                    pad.assetCategory !== 'site' ? 'bg-purple-100 text-purple-700' : 'bg-gray-100 text-gray-500',
                  )}
                >
                  <option value="site">Normal pad/site</option>
                  <option value="rig">Drilling rig (any operator)</option>
                  <option value="truck">Service truck (any operator)</option>
                  <option value="other_mobile">Other mobile asset (any operator)</option>
                  <option value="gas_plant">Gas plant</option>
                  <option value="tank_battery">Tank battery</option>
                  <option value="compressor_station">Compressor station</option>
                  <option value="swd_facility">SWD facility</option>
                  <option value="office">Office</option>
                  <option value="shop">Shop</option>
                </select>
              ) : pad.assetCategory !== 'site' ? (
                <span className="text-xs bg-purple-100 text-purple-700 px-2 py-0.5 rounded-full">
                  {ASSET_CATEGORY_LABELS[pad.assetCategory] || pad.assetCategory}
                </span>
              ) : null}
              {!pad.isActive && (
                <span className="text-xs bg-red-100 text-red-600 px-2 py-0.5 rounded-full">Inactive</span>
              )}
            </div>
          </div>
        </div>
      </div>

      {/* Location Info Card */}
      <div className="bg-white rounded-lg border border-gray-200 shadow-sm">
        <div className="px-4 py-3 border-b border-gray-100">
          <h2 className="text-sm font-semibold text-gray-700 flex items-center gap-2">
            <Compass className="w-4 h-4" /> Location Info
          </h2>
        </div>
        <div className="px-4 py-3 space-y-2 text-sm">
          {strLabel && (
            <div className="flex items-center gap-2">
              <MapPin className="w-4 h-4 text-gray-400 flex-shrink-0" />
              <span className="text-gray-700">{strLabel}</span>
            </div>
          )}
          {pad.county && (
            <div className="flex items-center gap-2">
              <MapPin className="w-4 h-4 text-gray-400 flex-shrink-0" />
              <span className="text-gray-700">{pad.county} County</span>
            </div>
          )}
          {hasGps && (
            <div className="flex items-center gap-2">
              <Navigation className="w-4 h-4 text-gray-400 flex-shrink-0" />
              <a
                href={`https://maps.google.com/?q=${pad.latitude},${pad.longitude}`}
                target="_blank"
                rel="noopener noreferrer"
                className="text-blue-600 hover:underline"
              >
                {parseFloat(pad.latitude!).toFixed(5)}, {parseFloat(pad.longitude!).toFixed(5)}
              </a>
            </div>
          )}
          {pad.directions && (
            <div className="mt-2 p-2 bg-gray-50 rounded text-xs text-gray-600">
              <span className="font-medium">Directions:</span> {pad.directions}
            </div>
          )}
          {pad.accessNotes && (
            <div className="p-2 bg-amber-50 rounded text-xs text-amber-700">
              <span className="font-medium">Access Notes:</span> {pad.accessNotes}
            </div>
          )}
          {/* Facility Code (Enverus charge-to) */}
          <div className="flex items-center gap-2 pt-1">
            <Tag className="w-4 h-4 text-gray-400 flex-shrink-0" />
            {editingFacility ? (
              <>
                <input
                  type="text"
                  value={facilityDraft}
                  onChange={e => setFacilityDraft(e.target.value)}
                  placeholder="Facility code (e.g. FC17708)"
                  autoFocus
                  className="flex-1 border border-gray-300 rounded px-2 py-1 text-sm focus:ring-1 focus:ring-blue-500"
                  onKeyDown={e => { if (e.key === 'Enter') handleSaveFacility(); if (e.key === 'Escape') setEditingFacility(false) }}
                />
                <button onClick={handleSaveFacility} disabled={savingFacility} className="text-xs text-blue-600 hover:underline disabled:opacity-50">Save</button>
                <button onClick={() => setEditingFacility(false)} className="text-xs text-gray-400 hover:text-gray-600">Cancel</button>
              </>
            ) : (
              <>
                <span className="text-gray-500">Facility Code:</span>
                <span className="text-gray-700">{pad.facilityCode || <span className="text-gray-400 italic">none</span>}</span>
                {canManage && (
                  <button
                    onClick={() => { setFacilityDraft(pad.facilityCode || ''); setEditingFacility(true) }}
                    className="text-xs text-blue-600 hover:underline ml-1"
                  >
                    {pad.facilityCode ? 'Edit' : 'Add'}
                  </button>
                )}
              </>
            )}
          </div>
          {!strLabel && !pad.county && !hasGps && !pad.directions && !pad.accessNotes && !pad.facilityCode && (
            <p className="text-gray-400 italic">No location details on file.</p>
          )}
          {azureLocationId && (
            <p className="text-xs text-gray-400">Azure Location ID: {azureLocationId}</p>
          )}
        </div>
      </div>

      {/* Wells Card */}
      <div className="bg-white rounded-lg border border-gray-200 shadow-sm">
        <div className="px-4 py-3 border-b border-gray-100 flex items-center justify-between">
          <h2 className="text-sm font-semibold text-gray-700 flex items-center gap-2">
            <Droplets className="w-4 h-4" /> Wells
            <span className="text-xs text-gray-400 font-normal">({pad.wells.length})</span>
          </h2>
          {canManage && (
            <button onClick={() => setShowAddWell(true)} className="text-xs text-blue-600 hover:text-blue-800 flex items-center gap-1">
              <Plus className="w-3.5 h-3.5" /> Add Well
            </button>
          )}
        </div>
        <div className="divide-y divide-gray-100">
          {pad.wells.length === 0 ? (
            <p className="px-4 py-6 text-sm text-gray-400 text-center italic">No active wells on this pad.</p>
          ) : (
            pad.wells.map(well => (
              <div key={well.id} className="px-4 py-3">
                <div className="flex items-center gap-3">
                  <button
                    onClick={() => navigate(`/locations/wells/${well.id}`)}
                    className="flex items-center gap-3 flex-1 min-w-0 hover:bg-gray-50 rounded -m-1 p-1 transition-colors"
                  >
                    <div className="w-8 h-8 rounded-lg bg-blue-50 flex items-center justify-center flex-shrink-0">
                      <Droplets className="w-4 h-4 text-blue-500" />
                    </div>
                    <div className="flex-1 min-w-0">
                      <div className="flex items-center gap-2">
                        <span className="text-sm font-medium text-gray-800 truncate">{well.wellName || 'Unnamed Well'}</span>
                        {well.wellStatus && (
                          <span className={cn(
                            'text-xs px-1.5 py-0.5 rounded font-medium',
                            well.wellStatus === 'A' ? 'bg-green-100 text-green-700' :
                            well.wellStatus === 'PA' ? 'bg-red-100 text-red-600' :
                            'bg-gray-100 text-gray-600'
                          )}>
                            {WELL_STATUS_LABELS[well.wellStatus] || well.wellStatus}
                          </span>
                        )}
                        {well.isHighRisk && (
                          <Shield className="w-3.5 h-3.5 text-red-500 flex-shrink-0" />
                        )}
                      </div>
                      <div className="flex items-center gap-3 text-xs text-gray-500 mt-0.5">
                        {well.apiNumber && <span>API: {well.apiNumber}</span>}
                        {well.wellType && <span>{WELL_TYPE_LABELS[well.wellType] || well.wellType}</span>}
                        {well.hasSuppliedAir && (
                          <span className="flex items-center gap-0.5 text-blue-600">
                            <Wind className="w-3 h-3" /> Air
                          </span>
                        )}
                      </div>
                    </div>
                    <ChevronRight className="w-4 h-4 text-gray-300 flex-shrink-0" />
                  </button>
                  {/* Move/Unassign buttons */}
                  {canManage && movingWellId !== well.id && (
                    <button
                      onClick={() => { setMovingWellId(well.id); setPadSearch(''); setPadResults([]) }}
                      className="p-1.5 text-gray-400 hover:text-blue-600 hover:bg-blue-50 rounded transition-colors"
                      title="Move to another pad"
                    >
                      <ArrowRightLeft className="w-4 h-4" />
                    </button>
                  )}
                </div>
                {/* Inline move UI */}
                {canManage && movingWellId === well.id && (
                  <div className="mt-2 ml-11 bg-blue-50 border border-blue-200 rounded-lg p-3 space-y-2">
                    <div className="flex items-center justify-between">
                      <span className="text-xs font-medium text-blue-700">Move well to:</span>
                      <button onClick={() => setMovingWellId(null)} className="text-gray-400 hover:text-gray-600">
                        <X className="w-4 h-4" />
                      </button>
                    </div>
                    <div className="relative">
                      <Search className="absolute left-2.5 top-2 w-4 h-4 text-gray-400" />
                      <input
                        type="text"
                        value={padSearch}
                        onChange={e => setPadSearch(e.target.value)}
                        placeholder="Search pads..."
                        className="w-full pl-8 pr-3 py-1.5 text-sm border border-gray-300 rounded focus:outline-none focus:ring-1 focus:ring-blue-500"
                        autoFocus
                      />
                    </div>
                    {padSearching && (
                      <div className="text-xs text-gray-500 flex items-center gap-1">
                        <Loader2 className="w-3 h-3 animate-spin" /> Searching...
                      </div>
                    )}
                    {padResults.length > 0 && (
                      <div className="max-h-40 overflow-y-auto space-y-1">
                        {padResults.map(p => (
                          <button
                            key={p.id}
                            onClick={() => handleMoveToPad(well.id, p.id)}
                            className="w-full text-left text-sm px-2 py-1.5 rounded hover:bg-blue-100 text-gray-700 flex items-center gap-2"
                          >
                            <Layers className="w-3.5 h-3.5 text-emerald-500 flex-shrink-0" />
                            <span className="truncate">{p.name}</span>
                          </button>
                        ))}
                      </div>
                    )}
                    <button
                      onClick={() => handleUnassignWell(well.id)}
                      className="w-full text-left text-xs px-2 py-1.5 rounded hover:bg-red-100 text-red-600 flex items-center gap-2"
                    >
                      <Unlink className="w-3.5 h-3.5" /> Remove from this pad (unassign)
                    </button>
                  </div>
                )}
              </div>
            ))
          )}
        </div>
      </div>

      <LocationWorkPointEditor
        workPoints={pad.workPoints}
        canManage={canManage}
        padId={pad.id}
        onChanged={loadPad}
      />

      {/* Footer metadata */}
      <div className="text-xs text-gray-400 text-center pb-4">
        Created {formatDate(pad.createdAt)} &middot; Last updated {formatDate(pad.updatedAt)}
        {pad.autoGenerated && ' &middot; Auto-generated'}
      </div>

      {/* Add Well Modal */}
      {showAddWell && pad && (
        <AddWellModal
          padId={pad.id}
          padName={pad.name}
          operatorId={pad.currentOperator?.id}
          onCreated={(_well) => {
            setShowAddWell(false)
            loadPad()  // Refresh to show new well
          }}
          onClose={() => setShowAddWell(false)}
        />
      )}
    </div>
  )
}
